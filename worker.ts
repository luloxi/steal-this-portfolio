/**
 * Worker entry: canonical host redirect, then the OpenNext (Next.js) handler.
 * www.lulox.com.ar -> https://lulox.com.ar (301). lulox.dev and www.lulox.dev are
 * redirected to lulox.com.ar by a Redirect Rule on the lulox.dev zone.
 * Scanner probes (see src/lib/junk-paths.ts) get a tiny 404 before Next runs.
 * Per-IP bursts get a tiny 429 (src/lib/rate-limit.ts); the owner and accounts marked "sin límite" are exempt.
 * /api/mcp/* is an API path (same bucket). It is not a junk path, and the page proxy does not run on it.
 *
 * McpRpc is a named WorkerEntrypoint for lulox-mcp (service binding only). It is not
 * mounted on fetch. Each method calls the OpenNext handler directly, so the www redirect,
 * the junk 404 and the per-IP rate limit do not run on that internal request.
 */
// @ts-expect-error generated by `opennextjs-cloudflare build`
import { default as handler } from "./.open-next/worker.js";
import { WorkerEntrypoint } from "cloudflare:workers";
import { isJunkPath } from "./src/lib/junk-paths";
import { createDraft, getPost, listPosts, publishPost, uploadImage } from "./src/lib/mcp-rpc";
import { rateLimited, type RateEnv } from "./src/lib/rate-limit";

type McpEnv = { MCP_SERVICE_TOKEN?: string };

function fetchMcp(env: unknown, ctx: unknown, request: Request) {
  return handler.fetch(request, env, ctx);
}

/** lulox-mcp service binding. RPC only: this class is not mounted on the default fetch handler. */
export class McpRpc extends WorkerEntrypoint<McpEnv> {
  uploadImage(input: unknown) {
    return uploadImage((request) => fetchMcp(this.env, this.ctx, request), this.env.MCP_SERVICE_TOKEN, input);
  }

  createDraft(input: unknown) {
    return createDraft((request) => fetchMcp(this.env, this.ctx, request), this.env.MCP_SERVICE_TOKEN, input);
  }

  publishPost(input: unknown) {
    return publishPost((request) => fetchMcp(this.env, this.ctx, request), this.env.MCP_SERVICE_TOKEN, input);
  }

  listPosts(input: unknown) {
    return listPosts((request) => fetchMcp(this.env, this.ctx, request), this.env.MCP_SERVICE_TOKEN, input);
  }

  getPost(input: unknown) {
    return getPost((request) => fetchMcp(this.env, this.ctx, request), this.env.MCP_SERVICE_TOKEN, input);
  }
}

export default {
  async fetch(request: Request, env: unknown, ctx: unknown) {
    const url = new URL(request.url);
    if (url.hostname === "www.lulox.com.ar") {
      url.hostname = "lulox.com.ar";
      url.protocol = "https:";
      return Response.redirect(url.toString(), 301);
    }
    // Scanner probes (/.env, /%2F.github, *.php ...): tiny 404, never a Next render (CPU limit).
    if (isJunkPath(url.pathname)) {
      return new Response("Not found", { status: 404, headers: { "content-type": "text/plain; charset=utf-8", "cache-control": "public, max-age=300" } });
    }
    const blocked = await rateLimited(request, url.pathname, env as RateEnv);
    if (blocked) return blocked;
    return handler.fetch(request, env, ctx);
  },
};

